"""Reading the mod list from a Mod Organizer 2 profile."""

import pytest

from foggymap.mo2 import read_profile


def _instance(tmp_path, modlist: str, mods: dict[str, list[str]], ini: str | None = None):
    """An MO2 instance: profiles/<name>/modlist.txt and a mods folder with files."""
    profile = tmp_path / "profiles" / "Main"
    profile.mkdir(parents=True)
    (profile / "modlist.txt").write_text(modlist, encoding="utf-8")
    mods_dir = tmp_path / (ini and "elsewhere" or "mods")
    for name, files in mods.items():
        for file in files:
            path = mods_dir / name / file
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(b"")
    if ini:
        (tmp_path / "ModOrganizer.ini").write_text(ini, encoding="utf-8")
    return profile


# modlist.txt lists the highest priority first: the reverse of MO2's left pane.
MODLIST = """# This file was automatically generated by Mod Organizer.
+Scrap Stacks
-Disabled Thing
+Loot Logic
-Loot QoL_separator
+Better Textures
+Unsofficial Patch
-Essentials_separator
+Loose Before Any Separator
*DLC: Automatron
*Creation Club: ccBGSFO4044-HellfirePowerArmor
"""

FILES = {
    "Scrap Stacks": ["ScrapStacks.esp"],
    "Loot Logic": ["mr Loot Logic and Reduction.esp", "F4SE/Plugins/LootLogic.dll", "readme.txt"],
    "Better Textures": ["Textures/rock.dds"],
    "Unsofficial Patch": ["unofficial fallout 4 patch.esp", "unofficial fallout 4 patch - main.ba2"],
    "Loose Before Any Separator": ["Scripts/thing.pex"],
}


@pytest.fixture
def profile(tmp_path):
    return _instance(tmp_path, MODLIST, FILES)


def test_groups_follow_the_separators_in_mo2s_own_order(profile):
    groups = read_profile(profile)["groups"]

    assert [(g["label"], [m["name"] for m in g["mods"]]) for g in groups] == [
        ("Unsorted", ["Loose Before Any Separator"]),
        ("Essentials", ["Unsofficial Patch", "Better Textures"]),
        ("Loot QoL", ["Loot Logic", "Scrap Stacks"]),
    ]


def test_disabled_mods_are_left_out(profile):
    names = [m["name"] for g in read_profile(profile)["groups"] for m in g["mods"]]

    assert "Disabled Thing" not in names


def test_each_mod_lists_its_plugins_and_script_extender_dlls(profile):
    mods = {m["name"]: m for g in read_profile(profile)["groups"] for m in g["mods"]}

    assert mods["Loot Logic"]["plugins"] == ["mr Loot Logic and Reduction.esp"]
    assert mods["Loot Logic"]["dlls"] == ["LootLogic.dll"]
    assert mods["Better Textures"]["plugins"] == [] and mods["Better Textures"]["dlls"] == []


def test_game_content_mo2_does_not_manage_is_listed_apart(profile):
    assert read_profile(profile)["unmanaged"] == ["DLC: Automatron",
                                                  "Creation Club: ccBGSFO4044-HellfirePowerArmor"]


def test_counts_enabled_mods(profile):
    assert read_profile(profile)["enabled"] == 5


def test_a_mods_folder_moved_in_mo2s_settings_is_followed(tmp_path):
    ini = "[Settings]\nmod_directory=" + str(tmp_path / "elsewhere").replace("\\", "/") + "\n"
    profile = _instance(tmp_path, MODLIST, FILES, ini=ini)

    mods = {m["name"]: m for g in read_profile(profile)["groups"] for m in g["mods"]}

    assert mods["Scrap Stacks"]["plugins"] == ["ScrapStacks.esp"]


def test_a_missing_mod_folder_still_lists_the_mod(tmp_path):
    profile = _instance(tmp_path, "+Ghost Mod\n", {})

    (group,) = read_profile(profile)["groups"]

    assert group["mods"] == [{"name": "Ghost Mod", "plugins": [], "dlls": []}]


def test_a_profile_without_a_mod_list_is_an_error(tmp_path):
    with pytest.raises(FileNotFoundError):
        read_profile(tmp_path)
