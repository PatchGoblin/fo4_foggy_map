"""Regenerate site/icons.js: the Lucide icons the published map uses for locations.

    python tools/fetch_icons.py

The icons are copied into the site rather than loaded from a CDN, so the page has no
third-party dependency at view time. Rerun this after changing ``MARKER_KINDS``; a test
fails if the page is missing an icon the table names.
"""

from __future__ import annotations

import json
import os
import re
import sys
import urllib.request

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "viewer"))

from foggymap.publish import MARKER_KINDS, UNKNOWN_KIND, default_template_dir  # noqa: E402

LUCIDE_VERSION = "0.460.0"
BASE_URL = "https://cdn.jsdelivr.net/npm/lucide-static@{version}"


def icon_names() -> list[str]:
    return sorted({icon for icon, _ in MARKER_KINDS.values()} | {UNKNOWN_KIND[0]})


def svg_body(svg: str) -> str:
    """The drawing elements inside an icon's <svg>, on one line."""
    match = re.search(r"<svg\b[^>]*>(.*)</svg>", svg, re.S)
    if not match:
        raise ValueError("not an SVG icon")
    return "".join(line.strip() for line in match.group(1).splitlines() if line.strip())


def build_icons_js(bodies: dict[str, str], version: str, licence: str) -> str:
    notice = "\n".join(f"// {line}".rstrip() for line in licence.strip().splitlines())
    return (
        f"// Generated by tools/fetch_icons.py from lucide-static@{version}. Do not edit.\n"
        "//\n"
        f"{notice}\n"
        "\n"
        "// Each value is the inside of a 24x24 Lucide <svg>, drawn with stroke=currentColor.\n"
        f"const ICONS = {json.dumps(bodies, indent=2, sort_keys=True)};\n"
    )


def fetch_icons(names: list[str], version: str = LUCIDE_VERSION, get=None) -> str:
    get = get or _get
    base = BASE_URL.format(version=version)
    bodies = {name: svg_body(get(f"{base}/icons/{name}.svg")) for name in names}
    return build_icons_js(bodies, version, get(f"{base}/LICENSE"))


def _get(url: str) -> str:
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read().decode("utf-8")


def main() -> int:
    script = fetch_icons(icon_names())
    path = os.path.join(default_template_dir(), "icons.js")
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(script)
    print(f"wrote {len(icon_names())} icons to {os.path.relpath(path)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
